/**
 * DL-01: the hosts whose links open in the app, verified by Android against each one's
 * `/.well-known/assetlinks.json` (idejo IX-03). Android reads them from the manifest only, so
 * they are fixed at build time: the inbox and idejo.org's forums, plus any listed in the
 * `idejo.appLinkHosts` property (comma-separated, `*.` allowed) by whoever builds the app.
 * Links to other forums open in the browser.
 */
val appLinkHosts: List<String> =
    (
        listOf("my.idejo.org", "*.idejo.org") +
            providers
                .gradleProperty("idejo.appLinkHosts")
                .orElse("")
                .get()
                .split(',')
                .map { it.trim().lowercase() }
                .filter { it.isNotEmpty() }
    ).distinct().onEach { host ->
        require(
            Regex("""^(\*\.)?[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$""")
                .matches(host),
        ) { "idejo.appLinkHosts: not a host name: $host" }
    }

/** Writes the App Links intent filter (DL-01), merged into the app's manifest. */
abstract class AppLinksManifest : DefaultTask() {
    @get:Input abstract val hosts: ListProperty<String>

    @get:OutputFile abstract val manifest: RegularFileProperty

    @TaskAction
    fun write() {
        val android = "http://schemas.android.com/apk/res/android"
        val paths =
            listOf("/c/", "/t/", "/m/", "/u/", "/p/", "/unread", "/chat").joinToString("\n") {
                """                <data android:pathPrefix="$it" />"""
            }
        val hostLines =
            hosts.get().joinToString("\n") { """                <data android:host="$it" />""" }
        manifest.get().asFile.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by AppLinksManifest (DL-01) from idejo.appLinkHosts. -->
            |<manifest xmlns:android="$android">
            |    <application>
            |        <activity android:name="org.idejo.app.MainActivity" android:exported="true">
            |            <intent-filter android:autoVerify="true">
            |                <action android:name="android.intent.action.VIEW" />
            |                <category android:name="android.intent.category.DEFAULT" />
            |                <category android:name="android.intent.category.BROWSABLE" />
            |                <data android:scheme="https" />
            |$hostLines
            |                <data android:path="/" />
            |                <data android:path="/p" />
            |$paths
            |            </intent-filter>
            |        </activity>
            |    </application>
            |</manifest>
            |
            """.trimMargin(),
        )
    }
}

androidComponents {
    onVariants { variant ->
        val task =
            tasks.register<AppLinksManifest>("${variant.name}AppLinksManifest") {
                hosts.set(appLinkHosts)
                manifest.set(layout.buildDirectory.file("generated/appLinks/${variant.name}.xml"))
            }
        variant.sources.manifests.addGeneratedManifestFile(task, AppLinksManifest::manifest)
    }
}
